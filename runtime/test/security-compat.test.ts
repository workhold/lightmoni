test("query executor sends only checked canonical SQL, macro parameters and exact numeric strings to the reader", async () => {
  const seen: any[] = [],
    reader: any = {
      query: async (sql: string, params: any) => {
        seen.push({ sql, params });
        return {
          meta: [{ name: "value", type: "Int64" }],
          data: [{ value: parseJSON("9223372036854775807") }],
          rows: 1,
        };
      },
    },
    catalog: any = { list: async () => [{ name: "log_app" }] },
    q = new Executor(reader, catalog);
  const base = {
    range: {
      from: "2026-10-17T00:00:00.123456789Z",
      to: "2026-10-17T01:00:00Z",
    },
    interval_ms: 60000,
  };
  const result = await q.execute({
    ...base,
    queries: [
      {
        refId: "A",
        sql: "SELECT value /* fixture comment */ FROM log_app WHERE $__timeFilter(event_time) AND value={n:Int64}; -- tail",
        params: { n: { type: "Int64", value: "9223372036854775807" } },
      },
    ],
  });
  assert.equal(result.results[0].status, "success");
  assert.equal(result.results[0].frames[0].rows[0][0], "9223372036854775807");
  assert.equal(seen.length, 1);
  assert(!seen[0].sql.includes("fixture comment"));
  assert(!seen[0].sql.includes("--"));
  assert(!seen[0].sql.endsWith(";"));
  assert.equal(seen[0].params.__lm_from, "2026-10-17 00:00:00.123456789");
  assert.equal(seen[0].params.n, "9223372036854775807");
  await q.execute({
    ...base,
    queries: [
      { refId: "D", sql: "SELECT value FROM log_app WHERE value IN log_app" },
    ],
  });
  assert(seen[1].sql.includes("IN (log_app)"));
  seen.pop();
  const rejected = await q.execute({
    ...base,
    queries: [
      { refId: "B", sql: "SELECT * FROM log_app SETTINGS max_result_rows=0" },
      {
        refId: "C",
        sql: "SELECT * FROM log_app",
        params: { __lm_from: { type: "String", value: "override" } },
      },
    ],
  });
  assert(rejected.results.every((r) => r.status === "error"));
  assert.equal(seen.length, 1);
});
