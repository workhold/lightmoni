test("raster metadata matches Go fixtures and rejects forged CRC, malformed JPEG, unsafe formats", () => {
  assert.doesNotThrow(() => validateAvatar("data:image/png;base64," + png));
  assert.doesNotThrow(() => validateAvatar("data:image/jpeg;base64," + jpeg));
  const damaged = Buffer.from(png, "base64");
  damaged[29] ^= 1;
  assert.throws(() =>
    validateAvatar("data:image/png;base64," + damaged.toString("base64")),
  );
  for (const raw of [
    "data:image/svg+xml;base64,PHN2Zz4=",
    "data:image/png;base64,A",
    "data:image/jpeg;base64,/9j/wAADAAEAAQ==",
  ])
    assert.throws(() => validateAvatar(raw));
  for (const email of [
    "a..b@localhost",
    "a@example.com\r\nBcc:x@y",
    "Name <a@example.com>",
  ])
    assert.throws(() => validateContact({ email }));
  assert.equal(validateContact({ email: "a@localhost" }).email, "a@localhost");
});
async function supplier() {
  let identity: any = {
      id: "subject-1",
      name: "fixture",
      email: "sso@localhost",
    },
    redirectToken = false;
  const requests: { path: string; body: string; authorization?: string }[] = [];
  const server = createServer(async (req, res) => {
    let body = "";
    for await (const part of req) body += part;
    requests.push({
      path: req.url!,
      body,
      authorization: req.headers.authorization,
    });
    if (req.url === "/token" && redirectToken) {
      res.writeHead(302, { location: "/leak" });
      res.end();
      return;
    }
    res.setHeader("content-type", "application/json");
    res.end(
      req.url === "/token"
        ? '{"access_token":"fixture-access"}'
        : JSON.stringify(identity),
    );
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  const base = "http://127.0.0.1:" + (server.address() as any).port;
  return {
    base,
    requests,
    setIdentity: (v: any) => (identity = v),
    setRedirect: (v = true) => (redirectToken = v),
    close: () => new Promise<void>((r) => server.close(() => r())),
  };
}
