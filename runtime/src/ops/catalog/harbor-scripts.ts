  "        'job_loggers': ['STD_OUTPUT', 'FILE'],",
  "        'logger_sweeper_duration': 7,",
  "    },",
  "    'notification': {",
  "        'webhook_job_max_retry': 3,",
  "        'webhook_job_http_client_timeout': 3,",
