  "        raise ValueError(name + ' is missing or contains a newline')",
  "config = {",
  "    'hostname': parsed.hostname,",
  "    'external_url': public_url,",
  "    'http': {'port': 80},",
  "    'harbor_admin_password': os.environ['HARBOR_ADMIN_PASSWORD'],",
  "    'database': {",
  "        'password': os.environ['HARBOR_DB_PASSWORD'],",
  "        'max_idle_conns': 20,",
  "        'max_open_conns': 100,",
  "    },",
  "    'data_volume': '/data',",
  "    'jobservice': {",
